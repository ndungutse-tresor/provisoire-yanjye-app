// The app writes SQLite-style "?" placeholders; Postgres wants $1, $2, ...
const converted = new Map();
function toPg(sql) {
  let out = converted.get(sql);
  if (out) return out;
  let n = 0, quote = null;
  out = '';
  for (const ch of sql) {
    if (quote) { if (ch === quote) quote = null; out += ch; continue; }
    if (ch === "'" || ch === '"') { quote = ch; out += ch; continue; }
    out += ch === '?' ? '$' + ++n : ch;
  }
  converted.set(sql, out);
  return out;
}

// Same small interface over pg and PGlite: all / get / run / exec.
function wrap(query, execMany) {
  return {
    async all(sql, ...params) { return (await query(toPg(sql), params)).rows; },
    async get(sql, ...params) { return (await query(toPg(sql), params)).rows[0]; },
    async run(sql, ...params) { const r = await query(toPg(sql), params); return { changes: r.changes, rows: r.rows }; },
    exec: execMany
  };
}

let backend = null;

async function openPg(url) {
  const pg = require('pg');
  pg.types.setTypeParser(20, Number);     // bigint (ids, counts)
  pg.types.setTypeParser(1700, Number);   // numeric (AVG)
  const u = new URL(url);
  u.searchParams.delete('sslmode');
  const local = ['localhost', '127.0.0.1'].includes(u.hostname);
  const pool = new pg.Pool({
    connectionString: u.toString(),
    ssl: local ? false : { rejectUnauthorized: false },
    max: Number(process.env.DB_POOL) || 5,
    idleTimeoutMillis: 30000
  });
  pool.on('connect', (c) => { c.query(`SET search_path TO ${SCHEMA}`); });
  pool.on('error', (e) => console.error('Database connection error:', e.message));
  const q = (c) => async (sql, params) => { const r = await c.query(sql, params); return { rows: r.rows, changes: r.rowCount }; };
  return {
    db: wrap(q(pool), (sql) => pool.query(sql)),
    async tx(fn) {
      const c = await pool.connect();
      try {
        await c.query('BEGIN');
        const out = await fn(wrap(q(c), (sql) => c.query(sql)));
        await c.query('COMMIT');
        return out;
      } catch (e) {
        await c.query('ROLLBACK').catch(() => {});
        throw e;
      } finally {
        c.release();
      }
    },
    close: () => pool.end()
  };
}

async function openPglite(dir) {
  const { PGlite, types } = await import('@electric-sql/pglite');
  const lite = new PGlite(dir, { parsers: { [types.INT8]: Number, [types.NUMERIC]: Number } });
  await lite.waitReady;
  await lite.exec(`CREATE SCHEMA IF NOT EXISTS ${SCHEMA}; SET search_path TO ${SCHEMA}`);
  const q = (c) => async (sql, params) => { const r = await c.query(sql, params); return { rows: r.rows, changes: r.affectedRows || 0 }; };
  return {
    db: wrap(q(lite), (sql) => lite.exec(sql)),
    tx: (fn) => lite.transaction((t) => fn(wrap(q(t), (sql) => t.exec(sql)))),
    close: () => lite.close()
  };
}

// Call once before serving. Creates the tables when they are missing.
async function init() {
  if (backend) return;
  backend = process.env.DATABASE_URL
    ? await openPg(process.env.DATABASE_URL)
    : await openPglite(process.env.DB_DIR || path.join(DATA_DIR, 'pg'));
  await backend.db.exec(DDL);
}

// db.* and tx() are used after init().
const db = {
  all: (...a) => backend.db.all(...a),
  get: (...a) => backend.db.get(...a),
  run: (...a) => backend.db.run(...a),
  exec: (sql) => backend.db.exec(sql)
};
const tx = (fn) => backend.tx(fn);
const close = () => backend && backend.close();

